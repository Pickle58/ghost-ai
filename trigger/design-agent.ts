const designPlanSchema = z.object({
  status: z.enum(["ready", "fallback"]).default("ready"),
  summary: z.string().optional(),
  operations: z.array(
    z.object({
      type: z.enum([
        "add-node",
        "move-node",
        "resize-node",
        "update-node-data",
        "delete-node",
        "add-edge",
        "delete-edge",
      ]),
      id: z.string().min(1),
      label: z.string().optional(),
      shape: z.string().optional(),
      color: z.string().optional(),
      x: z.number().optional(),
      y: z.number().optional(),
      width: z.number().optional(),
      height: z.number().optional(),
      source: z.string().optional(),
      target: z.string().optional(),
    }),
  ),
});

function getDesignRoomSecret(): string {
  const secret = process.env.LIVEBLOCKS_SECRET_KEY;
  if (!secret) {
    throw new Error("LIVEBLOCKS_SECRET_KEY is not set");
  }

  return secret;
}

function getGoogleModel() {
  const apiKey = process.env.GOOGLE_AI_API_KEY ?? process.env.GOOGLE_GENERATIVE_AI_API_KEY;
  if (!apiKey) {
    return null;
  }

  const google = createGoogle({ apiKey });
  return google("gemini-3.8-flash");
}

export async function generateDesignPlanFromPrompt(
  prompt: string,
  canvas?: DesignCanvasSnapshot,
): Promise<DesignPlan> {
  const trimmed = prompt.trim();
  if (!trimmed) {
    return { status: "fallback", operations: [] };
  }

  const model = getGoogleModel();
  if (!model) {
    logger.info("Design plan using keyword fallback", {
      reason: "missing-google-api-key",
    });
    return buildDesignPlan(trimmed);
  }

  try {
    const result = await generateText({
      model,
      output: Output.object({ schema: designPlanSchema }),
      prompt: [
        "You create a valid collaborative architecture diagram from a user prompt.",
        "Return valid JSON using the supplied schema.",
        `Allowed node shapes: ${NODE_SHAPES.join(", ")}.`,
        `Allowed node fill colors: ${NODE_COLORS.map((color) => color.fill).join(", ")}.`,
        "Use add-node, move-node, resize-node, update-node-data, delete-node, add-edge, and delete-edge.",
        "Give every new node an explicit position and size. Space nodes at least 260px apart horizontally and 160px apart vertically.",
        "Keep labels short and architecture-specific.",
        canvas
          ? `Current canvas JSON: ${JSON.stringify(canvas)}`
          : "The canvas is currently empty.",
        `User request: ${trimmed}`,
      ].join("\n"),
    });

    if (!result.output) {
      logger.info("Design plan using keyword fallback", {
        reason: "empty-gemini-output",
      });
      return buildDesignPlan(trimmed);
    }

    logger.info("Design plan generated by Gemini", {
      operationCount: result.output.operations.length,
    });
    return normalizeDesignPlan(result.output as DesignPlan);
  } catch (error) {
    logger.warn("Design plan using keyword fallback", {
      reason: "gemini-error",
      message: error instanceof Error ? error.message : "unknown",
    });
    return buildDesignPlan(trimmed);
  }
}

async function ensureStatusFeed(liveblocks: Liveblocks, roomId: string): Promise<void> {
  try {
    await liveblocks.getFeed({ roomId, feedId: AI_STATUS_FEED_ID });
  } catch {
    try {
      await liveblocks.createFeed({
        roomId,
        feedId: AI_STATUS_FEED_ID,
        metadata: { kind: "status" },
      });
    } catch {
      // Another run may have created the feed first.
    }
  }
}

async function publishStatusMessage(
  liveblocks: Liveblocks,
  roomId: string,
  message: string,
  stage: AiStatusStage,
): Promise<void> {
  try {
    await ensureStatusFeed(liveblocks, roomId);
    const status = createAiStatusMessage(stage, message);
    await liveblocks.createFeedMessage({
      roomId,
      feedId: AI_STATUS_FEED_ID,
      data: {
        kind: status.kind,
        stage: status.stage,
        message: status.message,
        text: status.text,
        createdAt: status.createdAt,
      },
    });
  } catch {
    // Status is best-effort and must never block canvas updates.
  }
}

async function setAiPresence(
  liveblocks: Liveblocks,
  roomId: string,
  runId: string,
  thinking: boolean,
  cursor?: { x: number; y: number } | null,
): Promise<void> {
  await liveblocks.setPresence(roomId, createAiPresencePayload(runId, { thinking, cursor }));
}

async function clearAiPresence(
  liveblocks: Liveblocks,
  roomId: string,
  runId: string,
): Promise<void> {
  await liveblocks.setPresence(
    roomId,
    createAiPresencePayload(runId, { thinking: false, cursor: null, clear: true }),
  );
}

function toDesignCanvasSnapshot(
  flow: { nodes: CanvasNode[]; edges: CanvasEdge[] },
): DesignCanvasSnapshot {
  return {
    nodes: flow.nodes.map((node) => ({
      id: node.id,
      label: node.data.label,
      shape: node.data.shape,
      color: node.data.color,
      x: node.position.x,
      y: node.position.y,
    })),
    edges: flow.edges.map((edge) => ({
      id: edge.id,
      source: edge.source,
      target: edge.target,
      label: edge.data?.label,
    })),
  };
}

async function applyPlanToRoom(
  liveblocks: Liveblocks,
  roomId: string,
  plan: DesignPlan,
): Promise<void> {
  await mutateFlow<CanvasNode, CanvasEdge>({ client: liveblocks, roomId }, (flow) => {
    applyDesignOperations(flow, plan.operations);
  });
}

export const designAgent = schemaTask({
  id: "design-agent",
  schema: designAgentTaskSchema,
  retry: {
    maxAttempts: 1,
  },
  run: async (input) => {
    const prompt = input.prompt.trim();
    if (!prompt) {
      throw new AbortTaskRunError("Prompt is required");
    }

    const liveblocks = new Liveblocks({ secret: getDesignRoomSecret() });

    return executeDesignAgentRun(input, {
      generatePlan: async (nextPrompt) => {
        const canvas = toDesignCanvasSnapshot(
          await readCanvasSnapshot(liveblocks, input.roomId),
        );
        return generateDesignPlanFromPrompt(nextPrompt, canvas);
      },
      applyPlan: async (roomId, _runId, plan) => {
        await applyPlanToRoom(liveblocks, roomId, plan);
      },
      publishStatus: async (roomId, message, stage) => {
        await publishStatusMessage(liveblocks, roomId, message, stage);
      },
      setPresence: async (roomId, runId, thinking, cursor) => {
        await setAiPresence(liveblocks, roomId, runId, thinking, cursor);
      },
      clearPresence: async (roomId, runId) => {
        await clearAiPresence(liveblocks, roomId, runId);
      },
    });
  },
});

export interface DesignAgentQueuedResult extends DesignAgentTaskResult {
  publicToken: string;
  triggerRunId: string;
}

export async function designAgentTask(
  input: DesignAgentTaskInput,
): Promise<DesignAgentQueuedResult> {
  const handle = await tasks.trigger<typeof designAgent>("design-agent", input);

  return {
    runId: input.runId,
    projectId: input.projectId,
    roomId: input.roomId,
    userId: input.userId,
    prompt: input.prompt.trim(),
    status: "queued",
    message: `Design task accepted and queued for background processing. Trigger run: ${handle.id}`,
    publicToken: handle.publicAccessToken,
    triggerRunId: handle.id,
  };
}

export default designAgentTask;
